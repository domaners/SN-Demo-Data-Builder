#!/usr/bin/env node
'use strict';
// Builds the app from app/ into two committed outputs:
//   dist/ddb-<version>.xml        update set (System Update Sets > Import Update Set from XML)
//   servicenow/ + sn_source_control.properties
//                                 Studio source-control layout (Studio > Import From Source Control)
//
//   node build/build.js          write both
//   node build/build.js --check  fail if either is out of date

const fs = require('fs');
const path = require('path');
const { loadApp, ROOT } = require('./lib/source');
const { buildApp } = require('./lib/updateset');
const { checkWellFormed } = require('./lib/xmlcheck');

const SC_DIR = 'servicenow';

const PROPERTIES = [
	'#############################################################',
	'# This ServiceNow-created file contains the path to the app in this repo',
	'# path=<path to app content in your repo>',
	'# For example, if the app content resides in a folder named x_my_custom_app, the path value would be:',
	'# path=/x_my_custom_app',
	'# Update the path value when you move the app to a new repo location.',
	'############################################################',
	'#',
	'# Generated by build/build.js. The app lives in /' + SC_DIR + ' so Studio never touches the rest of the repo.',
	'path=/' + SC_DIR,
	''
].join('\n');

/** Every generated file: repo-relative path -> content. */
function outputs(src, result) {
	const files = {};
	files[path.join('dist', 'ddb-' + src.app.version + '.xml')] = result.xml;
	files['sn_source_control.properties'] = PROPERTIES;
	Object.keys(result.sourceControl).forEach((f) => {
		files[path.join(SC_DIR, f)] = result.sourceControl[f];
	});
	return files;
}

function listFiles(dir) {
	const abs = path.join(ROOT, dir);
	if (!fs.existsSync(abs))
		return [];
	const out = [];
	const walk = (rel) => {
		fs.readdirSync(path.join(ROOT, rel), { withFileTypes: true }).forEach((e) => {
			const p = path.join(rel, e.name);
			if (e.isDirectory())
				walk(p);
			else
				out.push(p);
		});
	};
	walk(dir);
	return out;
}

function main() {
	const check = process.argv.indexOf('--check') >= 0;
	const src = loadApp();
	const result = buildApp(src);
	checkWellFormed(result.xml);
	result.updates.forEach((u) => checkWellFormed(u.payload, u.name));
	Object.keys(result.sourceControl).filter((f) => f.endsWith('.xml'))
		.forEach((f) => checkWellFormed(result.sourceControl[f], f));

	const files = outputs(src, result);
	const stale = listFiles(SC_DIR).filter((f) => !(f in files));

	if (check) {
		const problems = Object.keys(files).filter((f) => {
			const abs = path.join(ROOT, f);
			return !fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== files[f];
		}).concat(stale);
		if (problems.length) {
			console.error('Generated files are out of date (' + problems.length + '), e.g. ' + problems.slice(0, 3).join(', ') +
				'. Run: npm run build');
			process.exit(1);
		}
		console.log('Generated files are up to date (' + result.updates.length + ' updates).');
		return;
	}

	stale.forEach((f) => fs.unlinkSync(path.join(ROOT, f)));
	Object.keys(files).forEach((f) => {
		const abs = path.join(ROOT, f);
		fs.mkdirSync(path.dirname(abs), { recursive: true });
		fs.writeFileSync(abs, files[f]);
	});
	console.log('Wrote dist/ddb-' + src.app.version + '.xml and ' + SC_DIR + '/ (' + result.updates.length +
		' updates, ' + Object.keys(result.sourceControl).length + ' files).');
}

module.exports = { outputs, SC_DIR };

if (require.main === module)
	main();
